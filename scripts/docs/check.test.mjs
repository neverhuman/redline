test('relative cargo target paths and unset or relative TMPDIR work through the real docs wrapper', () => {
  const root = mkdtempSync(join(fixtureRoot(), 'docs-wrapper-'));
  mkdirSync(join(root, 'scripts/docs'), { recursive: true });
  mkdirSync(join(root, 'bin'), { recursive: true });
  const script = process.env.REDLINE_DOCS_CHECK_SCRIPT ?? fileURLToPath(new URL('../check-docs.sh', import.meta.url));
  writeFileSync(join(root, 'scripts/check-docs.sh'), readFileSync(script));
  writeFileSync(join(root, 'bin/cargo'), '#!/usr/bin/env bash\nexit 0\n');
  chmodSync(join(root, 'bin/cargo'), 0o755);
  writeFileSync(join(root, 'scripts/docs/fetch-release.mjs'),
    `console.log(JSON.stringify({receipts:['v5.1.0','v5.1.1'].map(tag=>({tag,binary:${JSON.stringify(binary)},archive:process.argv.at(-1)+'/core.zip'}))}));\n`);
  for (const file of ['check-hardening.test.mjs', 'check.test.mjs']) writeFileSync(join(root, 'scripts/docs', file), '');
  writeFileSync(join(root, 'scripts/docs/check.mjs'),
    "import { writeFileSync } from 'node:fs'; writeFileSync('wrapper-result.json', JSON.stringify({tmpdir:process.env.TMPDIR,args:process.argv.slice(2)}));\n");
  for (const file of ['test-docs-quickstart.sh', 'test-package-ffi.sh']) writeFileSync(join(root, 'scripts', file), 'exit 0\n');
  const env = { ...process.env, CARGO_TARGET_DIR: 'target', PATH: `${join(root, 'bin')}:${process.env.PATH}` };
  for (const scratch of [undefined, 'target/relative-tmp']) {
    if (scratch === undefined) delete env.TMPDIR;
    else env.TMPDIR = scratch;
    const result = spawnSync('bash', [join(root, 'scripts/check-docs.sh')], { cwd: root, env, encoding: 'utf8' });
    assert.equal(result.status, 0, result.stderr);
    const receipt = JSON.parse(readFileSync(join(root, 'wrapper-result.json')));
    assert.equal(receipt.tmpdir, join(root, scratch ?? 'target/docs-check/tmp'));
    assert.equal(receipt.args[receipt.args.indexOf('--rlib') + 1], join(root, 'target/debug/libredlinedb.rlib'));
  }
});

test('the published new release opens the old physical backup and checks data plus integrity', () => {
  const oldBinary = process.env.REDLINE_DOCS_TEST_OLD_BINARY;
  assert.ok(oldBinary, 'set the verified v5.1.0 binary for the upgrade control');
  const contract = JSON.parse(readFileSync(process.env.REDLINE_DOCS_CONTRACT ?? 'scripts/docs/release-contract.json'));
  const overlay = process.env.REDLINE_DOCS_OVERLAY ? JSON.parse(readFileSync(process.env.REDLINE_DOCS_OVERLAY)) : {};
  const source = overlay['docs/upgrade-v5.1.1.md'] ?? readFileSync('docs/upgrade-v5.1.1.md', 'utf8');
  const receipts = upgradeChecks(binary, oldBinary, contract, source);
  const backup = receipts.find(receipt => receipt.label === 'upgrade-backup-v5.1.1');
  assert.ok(backup, 'new-release physical-backup execution receipt is required');
  assert.equal(backup.binary, binary);
  assert.equal(backup.stdout, '7|a\n20|saved\nok\n');
});
