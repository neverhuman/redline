const binary = process.env.REDLINE_DOCS_TEST_BINARY;
assert.ok(binary, 'set REDLINE_DOCS_TEST_BINARY to the verified published release');
const run = (body, info = 'sql doctest') => executeBlock(binary, { body, info }, 'negative-control');

test('an expected result is required, not just a successful exit', () => {
  run('SELECT 1;\n-- prints: 1\n');
  assert.throws(() => run('SELECT 1;\n-- prints: 999\n'), /AssertionError/);
  assert.throws(() => run('SELECT 1;\n'), /requires expected output/);
});
test('invalid SQL and invented flags are rejected', () => {
  assert.throws(() => run('SELECT missing;\n-- prints: 1\n'), /AssertionError/);
  assert.throws(() => run('redlinedb --invented-docs-option :memory: "SELECT 1;"\n# prints: 1\n', 'bash doctest'), /AssertionError/);
});
test('documented SQL errors are checked for exit and message', () => {
  run('SELECT missing;\n-- error: no such column: missing\n', 'sql doctest error');
  assert.throws(() => run('SELECT 1;\n-- error: no such column: missing\n', 'sql doctest error'), /AssertionError/);
});
test('unknown languages and modifiers cannot silently skip execution', () => {
  assert.throws(() => run('SELECT 1;', 'sh doctest'), /unsupported doctest language/);
  assert.throws(() => run('SELECT 1;', 'sql doctest ignored'), /unknown doctest modifier/);
});
test('fences preserve embedded shorter fences and reject unterminated blocks', () => {
  assert.equal(fencedBlocks('````text\n```\n````\n')[0].body, '```\n');
  assert.throws(() => fencedBlocks('```sql\nSELECT 1;'), /unclosed/);
});

test('missing or fabricated coverage blocks fail instead of becoming claims', () => {
  const templateFile = process.env.REDLINE_DOCS_KNOWN_TEMPLATE ?? 'scripts/docs/known-limitations.md.in';
  const template = readFileSync(templateFile, 'utf8');
  const source = renderKnownLimitations('.', template);
  checkCoverage('.', source, template);
  assert.match(source.slice(0, 500), /Generated by:.*DO NOT EDIT BY HAND/);
  const withoutHeader = source.replace(/^<!-- Generated by:[^\n]+-->\n\n/, '');
  assert.notEqual(withoutHeader, source);
  assert.throws(() => checkCoverage('.', withoutHeader, template), /generated page differs/);
  assert.throws(() => checkCoverage('.', '# Missing block', template), /missing generated coverage/);
  const invented = source.replace(/(\| sqlite_parity \| )\d+/, (_, prefix) => prefix + '999999');
  assert.notEqual(invented, source);
  assert.throws(() => checkCoverage('.', invented, template), /coverage differs/);
  const rql = renderRqlCoverage('.');
  checkRqlCoverage('.', rql);
  assert.throws(() => checkRqlCoverage('.', rql.replace(/passed \d+/, 'passed 999999')), /coverage differs/);
});

test('repository links reject missing pages and anchors', () => {
  checkLinks('.', 'README.md', '[guide](docs/install.md)');
  assert.throws(() => checkLinks('.', 'README.md', '[missing](docs/not-a-page.md)'), /missing link target/);
  assert.throws(() => checkLinks('.', 'README.md', '[missing](docs/install.md#not-an-anchor)'), /missing anchor/);
});

test('prose cannot restore a release claim disproved by its executable examples', () => {
  checkReleaseClaims(() => 'corrected guidance');
  assert.throws(() => checkReleaseClaims(file => file.endsWith('08-embed.md') ? '`--database` is an existing file' : 'corrected guidance'), /server creates a missing directory/);
});

test('new guides bind upgrade flags, release history and dated issues', () => {
  const input = name => readFileSync(process.env['REDLINE_DOCS_' + name] ?? 'scripts/docs/' + {
    CONTRACT: 'release-contract.json', ISSUES: 'issues.json',
  }[name], 'utf8');
  const contract = JSON.parse(input('CONTRACT'));
  const issues = JSON.parse(input('ISSUES'));
  const overlay = process.env.REDLINE_DOCS_OVERLAY ? JSON.parse(readFileSync(process.env.REDLINE_DOCS_OVERLAY)) : {};
  const read = file => overlay[file] ?? readFileSync(file, 'utf8');
  checkGuideClaims(read, contract, issues);
  const upgrade = read('docs/upgrade-v5.1.1.md');
  parseUpgradeRecipe(upgrade);
  assert.throws(() => parseUpgradeRecipe(upgrade.replace('--physical', '--physical-typo')), /unsupported command or backup flag/);
  assert.throws(() => checkGuideClaims(file => file === 'docs/upgrade-v5.1.1.md'
    ? read(file).replace(contract.releases['v5.1.1'].commit, '0'.repeat(40)) : read(file), contract, issues), /wrong stable source commit/);
  assert.throws(() => checkGuideClaims(file => file === 'docs/RELEASING.md'
    ? read(file).replace(String(contract.qualification.runs[0].id), '99999999999') : read(file), contract, issues), /wrong .* run/);
  assert.throws(() => checkGuideClaims(file => file === 'docs/RELEASING.md'
    ? read(file).replace(contract.qualification.sourceInputsSha256, '0'.repeat(64)) : read(file), contract, issues), /wrong stable source-input hash/);
  assert.throws(() => checkGuideClaims(file => file === 'docs/known-limitations.md'
    ? read(file).replace('had no\nopen issues', 'had 99\nopen issues') : read(file), contract, issues), /issue count\/date differs/);
  assert.throws(() => checkGuideClaims(file => file === 'docs/known-limitations.md'
    ? read(file) + '\nSerializable isolation is refused.' : read(file), contract, issues), /SQL accepts serializable/);
});

